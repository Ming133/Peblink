const exactTranslations: Record<"fr" | "zh", Map<string, string>> = {
  fr: new Map(entries.map(([english, french]) => [english, french])),
  zh: new Map(entries.map(([english, , chinese]) => [english, chinese])),
};

const segmentEntries = [...entries].sort((a, b) => b[0].length - a[0].length);

function isWordCharacter(value: string | undefined) {
  return Boolean(value && /[A-Za-z0-9]/.test(value));
}

function translateSegments(value: string, locale: "fr" | "zh") {
  let result = "";
  let index = 0;
  while (index < value.length) {
    let match: TranslationEntry | undefined;
    for (const entry of segmentEntries) {
      const english = entry[0];
      if (!value.startsWith(english, index)) continue;
      const before = index > 0 ? value[index - 1] : undefined;
      const after = value[index + english.length];
      if (isWordCharacter(english[0]) && isWordCharacter(before)) continue;
      if (isWordCharacter(english[english.length - 1]) && isWordCharacter(after)) continue;
      match = entry;
      break;
    }
    if (!match) {
      result += value[index];
      index += 1;
      continue;
    }
    result += locale === "fr" ? match[1] : match[2];
    index += match[0].length;
  }
  return result;
}

function translateDynamic(value: string, locale: "fr" | "zh") {
  const patterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = locale === "fr" ? [
    [/^(\d+) of (\d+) layers visible$/, match => `${match[1]} couches sur ${match[2]} visibles`],
    [/^(\d+) layers visible$/, match => `${match[1]} couches visibles`],
    [/^(\d+) targets match current filters$/, match => `${match[1]} cibles correspondent aux filtres actuels`],
    [/^(\d+) target areas$/, match => `${match[1]} zones cibles`],
    [/^(\d+)\/2 selected$/, match => `${match[1]}/2 sélectionnées`],
    [/^Select (\d+) more areas?$/, match => `Sélectionnez encore ${match[1]} zone${match[1] === "1" ? "" : "s"}`],
    [/^Level (\d+)$/, match => `Niveau ${match[1]}`],
    [/^LEVEL (\d+)$/, match => `NIVEAU ${match[1]}`],
    [/^(.*) confidence$/, match => `Confiance ${translateSegments(match[1], "fr").toLowerCase()}`],
    [/^Open (.*)$/, match => `Ouvrir ${match[1]}`],
    [/^View source for (.*)$/, match => `Voir la source de ${translateSegments(match[1], "fr")}`],
    [/^Select exploration target (.*)$/, match => `Sélectionner la cible d’exploration ${match[1]}`],
    [/^Remove (.*) from comparison$/, match => `Retirer ${match[1]} de la comparaison`],
  ] : [
    [/^(\d+) of (\d+) layers visible$/, match => `${match[2]}个图层中${match[1]}个可见`],
    [/^(\d+) layers visible$/, match => `${match[1]}个图层可见`],
    [/^(\d+) targets match current filters$/, match => `${match[1]}个目标区符合当前筛选条件`],
    [/^(\d+) target areas$/, match => `${match[1]}个目标区`],
    [/^(\d+)\/2 selected$/, match => `已选择${match[1]}/2`],
    [/^Select (\d+) more areas?$/, match => `还需选择${match[1]}个区域`],
    [/^Level (\d+)$/, match => `级别 ${match[1]}`],
    [/^LEVEL (\d+)$/, match => `级别 ${match[1]}`],
    [/^(.*) confidence$/, match => `${translateSegments(match[1], "zh")}可信度`],
    [/^Open (.*)$/, match => `打开${match[1]}`],
    [/^View source for (.*)$/, match => `查看${translateSegments(match[1], "zh")}的来源`],
    [/^Select exploration target (.*)$/, match => `选择勘探目标区${match[1]}`],
    [/^Remove (.*) from comparison$/, match => `从比较中移除${match[1]}`],
  ];

  for (const [pattern, replacement] of patterns) {
    const match = value.match(pattern);
    if (match) return replacement(match);
  }
  return null;
}

export function translateText(value: string, locale: Locale) {
  if (locale === "en" || !value.trim()) return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const core = value.slice(leading.length, value.length - trailing.length);
  const exact = exactTranslations[locale].get(core);
  const translated = exact ?? translateDynamic(core, locale) ?? translateSegments(core, locale);
  return `${leading}${translated}${trailing}`;
}

export type TranslationMemory = { original: string; lastApplied: string };

export function advanceTranslation(memory: TranslationMemory | undefined, current: string, locale: Locale) {
  const nextMemory = memory || { original: current, lastApplied: current };
  if (current !== nextMemory.original && current !== nextMemory.lastApplied) nextMemory.original = current;
  const value = translateText(nextMemory.original, locale);
  nextMemory.lastApplied = value;
  return { memory: nextMemory, value };
}

const textTranslations = new WeakMap<Text, TranslationMemory>();
const attributeTranslations = new WeakMap<Element, Map<string, TranslationMemory>>();
const translatedAttributes = ["aria-label", "placeholder", "title"] as const;

function isExcluded(node: Node) {
  const element = node.nodeType === Node.ELEMENT_NODE ? node as Element : node.parentElement;
  return Boolean(element?.closest("script, style, [data-no-translate]"));
}

function applyTextNode(node: Text, locale: Locale) {
  if (isExcluded(node) || !node.data.trim()) return;
  const result = advanceTranslation(textTranslations.get(node), node.data, locale);
  textTranslations.set(node, result.memory);
  if (node.data !== result.value) node.data = result.value;
}

function applyElementAttributes(element: Element, locale: Locale) {
  if (isExcluded(element)) return;
  let translations = attributeTranslations.get(element);
  if (!translations) {
    translations = new Map();
    attributeTranslations.set(element, translations);
  }
  translatedAttributes.forEach(attribute => {
    const current = element.getAttribute(attribute);
    if (current === null) return;
    const result = advanceTranslation(translations!.get(attribute), current, locale);
    translations!.set(attribute, result.memory);
    if (current !== result.value) element.setAttribute(attribute, result.value);
  });
}

function applyNode(node: Node, locale: Locale) {
  if (isExcluded(node)) return;
  if (node.nodeType === Node.TEXT_NODE) {
    applyTextNode(node as Text, locale);
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  const element = node as Element;
  applyElementAttributes(element, locale);
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();
  while (current) {
    if (current.nodeType === Node.TEXT_NODE) applyTextNode(current as Text, locale);
    else applyElementAttributes(current as Element, locale);
    current = walker.nextNode();
  }
}

export function useDocumentTranslation(locale: Locale) {
  useEffect(() => {
    document.documentElement.lang = localeOptions.find(option => option.code === locale)?.htmlLang || "en";
    const root = document.querySelector(".app-shell");
    if (!root) return;
    applyNode(root, locale);
    const observer = new MutationObserver(mutations => {
      mutations.forEach(mutation => {
        if (mutation.type === "characterData") applyTextNode(mutation.target as Text, locale);
        if (mutation.type === "attributes") applyElementAttributes(mutation.target as Element, locale);
        mutation.addedNodes.forEach(node => applyNode(node, locale));
      });
    });
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...translatedAttributes] });
    return () => observer.disconnect();
  }, [locale]);
}
